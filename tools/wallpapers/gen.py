    p1 = (px + hh * (iy - my) / d, py - hh * (ix - mx) / d)
    p2 = (px - hh * (iy - my) / d, py + hh * (ix - mx) / d)
    crescent = (f"M{f(p1[0])},{f(p1[1])} A{mr},{mr} 0 1,0 {f(p2[0])},{f(p2[1])} "
                f"A{ir},{ir} 0 0,1 {f(p1[0])},{f(p1[1])} Z")
