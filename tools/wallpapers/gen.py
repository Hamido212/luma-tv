"""Generates Luma TV wallpapers as SVG (preview) and Android VectorDrawable XML from one scene description.

All motifs are original compositions drawn for Luma TV (Japanese woodblock-print inspired).
Coordinates: 1920x1080 viewport.
"""
import math
import random
import sys
from pathlib import Path

W, H = 1920, 1080


def f(v):
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def circle(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)} A{f(r)},{f(r)} 0 1,0 {f(cx + r)},{f(cy)} A{f(r)},{f(r)} 0 1,0 {f(cx - r)},{f(cy)} Z"


def rect(x, y, w, h):
    return f"M{f(x)},{f(y)} H{f(x + w)} V{f(y + h)} H{f(x)} Z"


def pill(x, y, w, h):
    r = h / 2
    return (f"M{f(x + r)},{f(y)} H{f(x + w - r)} A{f(r)},{f(r)} 0 0,1 {f(x + w - r)},{f(y + h)} "
            f"H{f(x + r)} A{f(r)},{f(r)} 0 0,1 {f(x + r)},{f(y)} Z")


def poly(points, close=True):
    d = "M" + " L".join(f"{f(x)},{f(y)}" for x, y in points)
    return d + (" Z" if close else "")


def smooth(points, bottom=None):
    """Catmull-Rom through points -> cubic path; optionally closed down to y=bottom."""
    d = f"M{f(points[0][0])},{f(points[0][1])}"
    for i in range(len(points) - 1):
        p0 = points[i - 1] if i > 0 else points[i]
        p1, p2 = points[i], points[i + 1]
        p3 = points[i + 2] if i + 2 < len(points) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f" C{f(c1[0])},{f(c1[1])} {f(c2[0])},{f(c2[1])} {f(p2[0])},{f(p2[1])}"
    if bottom is not None:
        d += f" L{f(points[-1][0])},{f(bottom)} L{f(points[0][0])},{f(bottom)} Z"
    return d


def lin(x1, y1, x2, y2, *stops):
    return ("lin", x1, y1, x2, y2, stops)


def rad(cx, cy, r, *stops):
    return ("rad", cx, cy, r, stops)


class Scene:
    def __init__(self, name):
        self.name = name
        self.layers = []

    def add(self, d, fill, alpha=1.0, stroke=None, width=0):
        self.layers.append(dict(d=d, fill=fill, alpha=alpha, stroke=stroke, width=width))

    # ---- output
    def svg(self):
        defs, body = [], []
        for i, l in enumerate(self.layers):
            fill = l["fill"]
            if isinstance(fill, tuple):
                gid = f"g{i}"
                if fill[0] == "lin":
                    _, x1, y1, x2, y2, stops = fill
                    defs.append(f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">'
                                + "".join(f'<stop offset="{o}" stop-color="{c}" stop-opacity="{a}"/>' for o, c, a in stops)
                                + "</linearGradient>")
                else:
                    _, cx, cy, r, stops = fill
                    defs.append(f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{cx}" cy="{cy}" r="{r}">'
                                + "".join(f'<stop offset="{o}" stop-color="{c}" stop-opacity="{a}"/>' for o, c, a in stops)
                                + "</radialGradient>")
                paint = f"url(#{gid})"
            else:
                paint = fill or "none"
            if l["stroke"]:
                body.append(f'<path d="{l["d"]}" fill="none" stroke="{l["stroke"]}" stroke-width="{l["width"]}" '
                            f'stroke-linecap="round" stroke-linejoin="round" stroke-opacity="{l["alpha"]}"/>')
            else:
                body.append(f'<path d="{l["d"]}" fill="{paint}" fill-opacity="{l["alpha"]}"/>')
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">'
                f'<defs>{"".join(defs)}</defs>{"".join(body)}</svg>')

    def vector(self):
        def argb(c, a=1.0):
            return "#%02X%s" % (round(a * 255), c.lstrip("#").upper())
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               f'<!-- Luma TV wallpaper "{self.name}". Original vector artwork, generated by tools/wallpapers/gen.py. -->',
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
               '    xmlns:aapt="http://schemas.android.com/aapt"',
               '    xmlns:tools="http://schemas.android.com/tools"',
               '    tools:ignore="VectorRaster,VectorPath"',
               f'    android:width="960dp" android:height="540dp"',
               f'    android:viewportWidth="{W}" android:viewportHeight="{H}">']
        for l in self.layers:
            fill = l["fill"]
            if l["stroke"]:
                out.append(f'    <path android:pathData="{l["d"]}" android:strokeColor="{argb(l["stroke"])}" '
                           f'android:strokeAlpha="{l["alpha"]:.2f}" android:strokeWidth="{l["width"]}" '
                           'android:strokeLineCap="round" android:strokeLineJoin="round" />')
            elif isinstance(fill, tuple):
                out.append(f'    <path android:pathData="{l["d"]}" android:fillAlpha="{l["alpha"]:.2f}">')
                out.append('        <aapt:attr name="android:fillColor">')
                if fill[0] == "lin":
                    _, x1, y1, x2, y2, stops = fill
                    out.append(f'            <gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" '
                               f'android:endX="{x2}" android:endY="{y2}">')
                else:
                    _, cx, cy, r, stops = fill
                    out.append(f'            <gradient android:type="radial" android:centerX="{cx}" android:centerY="{cy}" '
                               f'android:gradientRadius="{r}">')
                for o, c, a in stops:
                    out.append(f'                <item android:offset="{o}" android:color="{argb(c, a)}" />')
                out.append('            </gradient>')
                out.append('        </aapt:attr>')
                out.append('    </path>')
            else:
                out.append(f'    <path android:pathData="{l["d"]}" android:fillColor="{argb(fill)}" '
                           f'android:fillAlpha="{l["alpha"]:.2f}" />')
        out.append('</vector>')
        return "\n".join(out) + "\n"


