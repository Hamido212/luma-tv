def stars(scene, rng, count, ymax, avoid=(), color="#F1ECDC"):
    buckets = {0.25: [], 0.45: [], 0.75: []}
    for _ in range(count):
        x, y = rng.uniform(0, W), rng.uniform(0, ymax) ** 1.0
        y = ymax * (rng.random() ** 1.6)
        if any(math.hypot(x - ax, y - ay) < ar for ax, ay, ar in avoid):
            continue
        r = rng.choice([1.1, 1.3, 1.6, 2.0, 2.4])
        a = rng.choice(list(buckets))
        buckets[a].append(circle(x, y, r))
    for a, parts in buckets.items():
        if parts:
            scene.add(" ".join(parts), color, a)


def scrims(scene, base="#0B0B16"):
    # Readability for the rows (lower half) and for the clock (upper left). Kept soft.
    scene.add(rect(0, 0, W, H), lin(0, 470, 0, H, (0, base, 0), (0.45, base, 0.42), (1, base, 0.78)))
    scene.add(rect(0, 0, W, H), rad(0, 0, 1150, (0, base, 0.55), (0.6, base, 0.18), (1, base, 0)))


def birds(scene, items, color, width=3.2):
    d = []
    for x, y, s in items:
        d.append(f"M{f(x - 14 * s)},{f(y - 5 * s)} Q{f(x - 6 * s)},{f(y - 7 * s)} {f(x)},{f(y)} "
                 f"Q{f(x + 6 * s)},{f(y - 7 * s)} {f(x + 14 * s)},{f(y - 5 * s)}")
    scene.add(" ".join(d), None, 0.9, stroke=color, width=width)


def wisp(x, y, w, h):
    """Tapered horizontal cloud band like in woodblock prints."""
    return (f"M{f(x)},{f(y + h * 0.5)} C{f(x + w * 0.2)},{f(y - h * 0.1)} {f(x + w * 0.8)},{f(y - h * 0.1)} {f(x + w)},{f(y + h * 0.45)} "
            f"C{f(x + w * 0.8)},{f(y + h * 1.05)} {f(x + w * 0.2)},{f(y + h * 1.1)} {f(x)},{f(y + h * 0.5)} Z")


def pagoda(x, base, s=1.0):
    parts = [rect(x - 46 * s, base - 14 * s, 92 * s, 14 * s)]
    y = base - 14 * s
    for i in range(5):
        hw = (74 - i * 9) * s
        body_w = hw * 0.52
        body_h = (24 - i * 1.5) * s
        parts.append(rect(x - body_w, y - body_h, 2 * body_w, body_h))
        y -= body_h
        lip = 9 * s
        parts.append(f"M{f(x - hw - lip)},{f(y - 2 * s)} Q{f(x - hw * 0.55)},{f(y + 1 * s)} {f(x - hw * 0.42)},{f(y - 12 * s)} "
                     f"L{f(x + hw * 0.42)},{f(y - 12 * s)} Q{f(x + hw * 0.55)},{f(y + 1 * s)} {f(x + hw + lip)},{f(y - 2 * s)} "
                     f"L{f(x + hw - 6 * s)},{f(y + 6 * s)} L{f(x - hw + 6 * s)},{f(y + 6 * s)} Z")
        y -= 12 * s
    parts.append(rect(x - 2.6 * s, y - 62 * s, 5.2 * s, 62 * s))
    for k in range(5):
        parts.append(rect(x - 7 * s, y - (14 + k * 9) * s, 14 * s, 3 * s))
    return " ".join(parts)


def cloud_pine(x, base, s):
    """Stylised garden pine: leaning trunk, curved branches, flat cloud-shaped needle pads."""
    tip = (x - 120 * s, base - 300 * s)
    trunk = (f"M{f(x - 12 * s)},{f(base)} C{f(x - 6 * s)},{f(base - 120 * s)} {f(x - 60 * s)},{f(base - 200 * s)} {f(tip[0] - 4 * s)},{f(tip[1])} "
             f"L{f(tip[0] + 6 * s)},{f(tip[1] + 2 * s)} C{f(x - 46 * s)},{f(base - 196 * s)} {f(x + 8 * s)},{f(base - 118 * s)} {f(x + 12 * s)},{f(base)} Z")
    pads, branches = [], []
    for (bx, by), (px, py, pw) in [((x - 34 * s, base - 150 * s), (x + 60 * s, base - 196 * s, 150 * s)),
                                   ((x - 76 * s, base - 222 * s), (x - 190 * s, base - 236 * s, 140 * s)),
                                   ((x - 100 * s, base - 270 * s), (x - 40 * s, base - 300 * s, 120 * s)),
                                   ((x - 8 * s, base - 80 * s), (x + 110 * s, base - 104 * s, 120 * s)),
                                   ((tip[0], tip[1]), (tip[0] - 30 * s, tip[1] - 24 * s, 110 * s))]:
        branches.append(f"M{f(bx)},{f(by)} Q{f((bx + px) / 2)},{f(min(by, py) - 18 * s)} {f(px)},{f(py)}")
        hgt = pw * 0.24
        pads.append(f"M{f(px - pw / 2)},{f(py)} C{f(px - pw / 2)},{f(py - hgt)} {f(px - pw / 5)},{f(py - hgt * 1.3)} {f(px)},{f(py - hgt * 1.05)} "
                    f"C{f(px + pw / 5)},{f(py - hgt * 1.35)} {f(px + pw / 2)},{f(py - hgt * 0.95)} {f(px + pw / 2)},{f(py)} "
                    f"C{f(px + pw * 0.28)},{f(py + hgt * 0.42)} {f(px - pw * 0.28)},{f(py + hgt * 0.42)} {f(px - pw / 2)},{f(py)} Z")
    return trunk, " ".join(branches), " ".join(pads)


def fir(x, ground, h):
    w = h * 0.55
    pts = [(x, ground - h), (x + w * 0.22, ground - h * 0.62), (x + w * 0.12, ground - h * 0.62),
           (x + w * 0.38, ground - h * 0.3), (x + w * 0.2, ground - h * 0.3), (x + w * 0.5, ground + 2),
           (x - w * 0.5, ground + 2), (x - w * 0.2, ground - h * 0.3), (x - w * 0.38, ground - h * 0.3),
           (x - w * 0.12, ground - h * 0.62), (x - w * 0.22, ground - h * 0.62)]
    return poly(pts)


def ridge_points(rng, y0, amp, step, x0=-40, x1=W + 40, rough=1.0):
    pts, x = [], x0
    phase = rng.uniform(0, 6.28)
    while x <= x1:
        y = y0 + amp * (0.55 * math.sin(x / 260 + phase) + 0.3 * math.sin(x / 97 + phase * 2) * rough
                        + 0.15 * rng.uniform(-1, 1) * rough)
        pts.append((x, y))
        x += step
    return pts


def height_at(pts, x):
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        if ax <= x <= bx:
            t = (x - ax) / (bx - ax)
            return ay + (by - ay) * t
    return pts[-1][1]


