    # crescent: outer circle minus offset inner circle
    ix, iy, ir = mx + 30, my - 18, 60
    d = math.hypot(ix - mx, iy - my)
    a = (mr ** 2 - ir ** 2 + d ** 2) / (2 * d)
    hh = math.sqrt(mr ** 2 - a ** 2)
