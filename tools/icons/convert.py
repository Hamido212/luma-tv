"""Convert monochrome SVG marks into Android VectorDrawables on a 240x240 viewport.

Each mark keeps its aspect ratio and is centred in the square, like the CSS mask renderer in
CleanFrame. Path data is normalised to absolute commands with arcs approximated by cubics, so
Android's path parser never meets compact SVG arc flags. Also writes ink metrics (visible bbox
and fill fraction inside it) measured from a raster of the same square.
"""
import json
import sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

from svgelements import SVG, Path as SPath, Shape, Matrix

N = 240


def shapes(svg_file):
    svg = SVG.parse(str(svg_file), reify=True)
    # svgelements already maps the viewBox onto a viewport of svg.width x svg.height.
    vw, vh = svg.width, svg.height
    k = N / max(vw, vh)
    ox = (N - vw * k) / 2
    oy = (N - vh * k) / 2
    to_square = Matrix(f"translate({ox},{oy}) scale({k})")
    out = []
    for el in svg.elements():
        if not isinstance(el, Shape):
            continue
        if el.values.get("visibility") == "hidden":
            continue
        p = SPath(el) * to_square
        p.reify()
        p.approximate_arcs_with_cubics()
        d = p.d(relative=False)
        if not d.strip():
            continue
        stroke = el.stroke is not None and el.stroke.value is not None and str(el.stroke) != "none"
        fill = el.fill is not None and el.fill.value is not None and str(el.fill) != "none"
        sw = (el.stroke_width or 0) * k if stroke else 0
        rule = el.values.get("fill-rule", "nonzero")
        out.append({"d": d, "fill": fill, "stroke": stroke, "sw": sw, "rule": rule,
                    "cap": el.values.get("stroke-linecap", "butt"),
                    "join": el.values.get("stroke-linejoin", "miter")})
    return out


def vector_xml(items):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/icons/convert.py; see NOTICE.md for the source and licence. -->',
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             f'    android:width="{N}dp" android:height="{N}dp"',
             f'    android:viewportWidth="{N}" android:viewportHeight="{N}">']
    for it in items:
        attrs = [f'android:pathData={quoteattr(it["d"])}']
        if it["fill"]:
            attrs.append('android:fillColor="#FFFFFFFF"')
            if it["rule"] == "evenodd":
                attrs.append('android:fillType="evenOdd"')
        if it["stroke"]:
            attrs.append('android:strokeColor="#FFFFFFFF"')
            attrs.append(f'android:strokeWidth="{it["sw"]:.3f}"')
            attrs.append(f'android:strokeLineCap="{it["cap"]}"')
            attrs.append(f'android:strokeLineJoin="{it["join"]}"')
        lines.append('    <path ' + '\n        '.join(attrs) + ' />')
    lines.append('</vector>')
    return "\n".join(lines) + "\n"


def main(src_dir, res_dir, metrics_out):
    src_dir, res_dir = Path(src_dir), Path(res_dir)
    res_dir.mkdir(parents=True, exist_ok=True)
    squares = {}
    for svg_file in sorted(src_dir.glob("*.svg")):
        items = shapes(svg_file)
        name = "mark_" + svg_file.stem
        (res_dir / f"{name}.xml").write_text(vector_xml(items), encoding="utf-8")
        squares[svg_file.stem] = items
    Path(metrics_out).write_text(json.dumps(squares), encoding="utf-8")
    print("converted", len(squares))


if __name__ == "__main__":
    main(*sys.argv[1:4])
